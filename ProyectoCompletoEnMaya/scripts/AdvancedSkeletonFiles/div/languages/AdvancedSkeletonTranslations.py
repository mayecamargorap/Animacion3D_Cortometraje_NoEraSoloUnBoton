def _language_index():

    if not cmds.optionVar(exists="asSettingsLanguage"):

        return None

    return LANGUAGE_INDEX.get(cmds.optionVar(query="asSettingsLanguage"))





def _translate(text, language_index):

    if not text:

        return text

    translated = EXACT_TRANSLATIONS.get(text)

    if translated:

        return translated[language_index]

    result = text

    for english, values in PARTIAL_TRANSLATIONS:

        result = result.replace(english, values[language_index])

    return result





def _is_advanced_skeleton_control(control):

    return "asFormLayout" in control.split("|")





def _apply_labels(language_index):

    for ui_type, command_name in LABEL_COMMANDS:

        command = getattr(cmds, command_name)

        try:

            controls = cmds.lsUI(type=ui_type, long=True) or []

        except Exception:

            continue

        for control in controls:

            if not _is_advanced_skeleton_control(control):

                continue

            try:

                label = command(control, query=True, label=True)

                translated = _translate(label, language_index)

                if translated != label:

                    command(control, edit=True, label=translated)

            except Exception:

                pass





def _apply_annotations(language_index):

    for control in cmds.lsUI(controls=True, long=True) or []:

        if not _is_advanced_skeleton_control(control):

            continue

        try:

            annotation = cmds.control(control, query=True, annotation=True)

            translated = _translate(annotation, language_index)

            if translated != annotation:

                cmds.control(control, edit=True, annotation=translated)

        except Exception:

            pass





def apply():

    language_index = _language_index()

    if language_index is None:

        return

    _apply_labels(language_index)

    _apply_annotations(language_index)

